/* v91.17.283 · WS8 · writes server/science/ from the served page: the page scripts named in keep.json (v91.17.283.20: by their id or a
   unique line of their code, never by position; checked by hash), verbatim except for the edits listed in keep.json (each an exact old -> new text that must
   occur once), and the JSON data blocks they read. node extract.mjs <artefact.html> <keep.json> */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pageBlocks, sha1 } from '../../../server/science/loader.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const SCI = join(ROOT, 'server', 'science');
const [ART, KEEP] = process.argv.slice(2);
const keep = JSON.parse(readFileSync(KEEP, 'utf8'));
const { blocks, json } = pageBlocks(ART);
const artHash = sha1(readFileSync(ART));
rmSync(join(SCI, 'modules'), { recursive: true, force: true }); rmSync(join(SCI, 'data'), { recursive: true, force: true });
mkdirSync(join(SCI, 'modules'), { recursive: true }); mkdirSync(join(SCI, 'data'), { recursive: true });
const modules = [], data = [];
/* v91.17.283.20 · the kept scripts are named by identity (keep.json v2: { id } or { anchor: a line of code that occurs in exactly one page
   script }), never by position: a selector that names no script or more than one stops the extraction. The modules keep the page order. */
const idOf = (b) => (b.attrs.match(/id="([^"]+)"/) || [])[1] || null;
const pick = (s) => { const hit = blocks.map((b, i) => [b, i]).filter(([b]) => (s.id ? idOf(b) === s.id : s.anchor ? b.code.includes(s.anchor) : false)).map(([, i]) => i);
  if (hit.length !== 1) throw new Error('keep.json selector ' + JSON.stringify(s).slice(0, 160) + ' names ' + hit.length + ' page scripts (exactly one is required)'); return hit[0]; };
if (keep.blocks.some((x) => typeof x !== 'object')) throw new Error('keep.json lists scripts by position; v91.17.283.20 requires { id } or { anchor } selectors');
const order = [...new Set(keep.blocks.map(pick))].sort((a, b) => a - b);
for (const i of order) {
  const b = blocks[i]; const id = (b.attrs.match(/id="([^"]+)"/) || [])[1] || null;
  let code = b.code; const from = { pageScript: i, sha1: sha1(b.code) }; const edits = [];
  for (const e of (keep.edits || []).filter(e => e.block === i)) {
    const n = code.split(e.old).length - 1; if (n !== 1) throw new Error('edit "' + e.why + '" matches ' + n + ' times in page script ' + i);
    code = code.replace(e.old, () => e.new); edits.push(e.why);
  }
  const file = String(modules.length).padStart(3, '0') + '-' + (id || 'page-script-' + i).replace(/[^a-z0-9-]+/gi, '-') + '.js';
  writeFileSync(join(SCI, 'modules', file), code);
  modules.push({ file, id, from, ...(edits.length ? { edits } : {}), sha1: sha1(code) });
}
for (const id of keep.data) { const file = id + '.json'; writeFileSync(join(SCI, 'data', file), json.get(id)); data.push({ id, file, sha1: sha1(json.get(id)) }); }
writeFileSync(join(SCI, 'manifest.json'), JSON.stringify({ version: keep.version, source: { artefact: ART.split('/').pop(), sha1: artHash, pageScripts: blocks.length },
  note: 'generated by scripts/tests283/ws8/extract.mjs; the modules run in this order in server/science/host.mjs', modules, data }, null, 1));
console.log('modules', modules.length, 'of', blocks.length, 'page scripts; data', data.length);
