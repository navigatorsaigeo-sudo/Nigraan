/* GEO281 (v91.17.283.18: on the one place table) · the reverse place name is the named OSM AREA that contains the point (owner, 19 Oct 2026 14:26 PKT:
   33.680860, 72.992720 is in F-11 but the start page said "G-11, Islamabad").
   Truth: scripts/tests281geo/truth40.json, generated by truth_points.py from OpenStreetMap polygons (random points inside named
   areas, half within 10-40 m of an edge; sector edges F-11|G-11 and F-10|F-11, Rawalpindi, Lahore DHA, Karachi Clifton, Peshawar,
   and Gilgit points that no named area contains). Nothing is typed in except the owner's reported coordinate.
   usage: node scripts/tests281geo/geo281.test.mjs [root]   (root defaults to this tree; on the v280.2 base it fails) */
import { readFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(process.argv[2] && !/^https?:/.test(process.argv[2]) ? process.argv[2] : join(HERE, '..', '..'));   /* the runner passes the server address: the tree is this one */
const DATA = join(ROOT, 'data');
let pass = 0, fail = 0; const ok = (c, m) => { if (c) pass++; else fail++; console.log((c ? 'PASS ' : 'FAIL ') + m); };

const { buildUnitIndex } = await import(join(ROOT, 'server/api/national.mjs'));
const settleF = join(DATA, 'settlement-elevation.json'); const settle = existsSync(settleF) ? JSON.parse(readFileSync(settleF, 'utf8')) : null;
const units = buildUnitIndex(JSON.parse(readFileSync(join(ROOT, 'server/contract/units.json'), 'utf8')), settle);
/* v91.17.283.18 · the area outlines are records of the one place table (data/geo/places.json.gz); the point resolver is places.mjs */
const { createPlaces, norm } = await import(join(ROOT, 'server/api/places.mjs'));
const log = console.log; console.log = () => {};
const P = createPlaces({ units, dataDir: DATA }); const G = { reverse: (la, lo) => P.resolvePoint(la, lo) };
const shown = (r) => { const p = r && r.place; return p ? p.name + (p.area && p.area !== p.name ? ', ' + p.area : '') : null; };   /* as the start page writes it */

/* 1 · the owner's point */
const own = G.reverse(33.680859957862594, 72.99272026); console.log = log;
ok(own && own.place && own.place.contained === true && /^F-11\b/.test(own.place.name), 'owner point 33.680860, 72.992720 is named by its containing area: ' + shown(own));
ok(own && !/G-11/.test(shown(own) || ''), 'owner point is not called G-11');
ok(own && own.unit && own.unit.by === 'polygon', 'its tehsil comes from the tehsil polygon, not the nearest centre');

/* 2 · 40 OSM-truth points */
const T = JSON.parse(readFileSync(join(HERE, 'truth40.json'), 'utf8'));
let good = 0; const bad = [];
for (const t of T) {
  console.log = () => {}; const r = G.reverse(t.lat, t.lon); console.log = log;
  const p = r && r.place;
  const right = t.truth == null ? !!p && p.contained === false && !/^in /.test(r.label || '')
    : !!p && p.contained === true && [p.name, ...(p.alt || [])].some((n) => norm(n) === norm(t.truth) || (t.truthLocal && norm(n) === norm(t.truthLocal)));
  if (right) good++; else bad.push(t.set + ' ' + t.lat + ',' + t.lon + ' truth=' + (t.truth || '(no area: must say near)') + ' got=' + shown(r));
}
ok(good === T.length, `OSM truth points named correctly: ${good}/${T.length}` + (bad.length ? '\n   ' + bad.join('\n   ') : ''));

/* 3 · honesty: a point no area contains is never presented as the place itself */
for (const t of T.filter((x) => x.truth == null)) { console.log = () => {}; const r = G.reverse(t.lat, t.lon); console.log = log;
  ok(r && r.place && r.place.contained === false && /^(Near |\d)/.test(r.place.name) && !/^at /.test(r.label), 'no containing area → "' + shown(r) + '" / label "' + r.label + '"'); }

/* 4 · speed and memory (warm) */
console.log = () => {}; G.reverse(T[0].lat, T[0].lon); console.log = log;
const N = 2000; const t0 = process.hrtime.bigint();
for (let i = 0; i < N; i++) { const t = T[i % T.length]; console.log = () => {}; G.reverse(t.lat + (i % 7) * 1e-5, t.lon); console.log = log; }
const ms = Number(process.hrtime.bigint() - t0) / 1e6 / N;
ok(ms <= 20, `warm reverse lookup ${ms.toFixed(3)} ms each (budget 20 ms)`);
{ const m = P.status(); ok(m && m.ready && m.cleaning && m.cleaning.area_outlines > 0, 'area outlines in the place table: ' + (m.cleaning && m.cleaning.area_outlines)); }

console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
