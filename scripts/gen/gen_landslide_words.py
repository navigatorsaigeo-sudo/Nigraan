#!/usr/bin/env python3
"""v91.17.283.8 (science audit) -- the landslide_odds class words of data/map-layer-scales.json, GENERATED from the held-out validation
of data/landslide-odds-model.json (validation.served.calibration: band, observedVsOrdinaryDay). The classes stay the model's ranking
bands (cuts 2 / 5 / 10 / 20, unchanged: the level does not move); the words name the ratio OBSERVED for days in each class, not the
model's own multiplier (the model ranks well, AUC 0.766, but a day it put at 5-10x happened 2.7x as often as an ordinary day).
Run: python3 scripts/gen/gen_landslide_words.py  (rewrites only layers.landslide_odds.words and .wordsBasis)."""
import json, os, re, sys
H = os.path.dirname(os.path.abspath(__file__)); D = os.path.join(H, '..', '..', 'data')
M = json.load(open(os.path.join(D, 'landslide-odds-model.json'), encoding='utf-8'))
cal = M['validation']['served']['calibration']
def r1(x): return int(x * 10 + 0.5 + 1e-9) / 10.0
def rng(b):
    m = re.match(r'^<\s*([\d.]+)$', b) or None
    if m: return (0.0, float(m.group(1)))
    m = re.match(r'^>=\s*([\d.]+)$', b)
    if m: return (float(m.group(1)), None)
    m = re.match(r'^([\d.]+)\s*-\s*([\d.]+)$', b)
    return (float(m.group(1)), float(m.group(2)))
B = [(rng(c['band']), r1(c['observedVsOrdinaryDay']), c['band']) for c in cal]
p = os.path.join(D, 'map-layer-scales.json'); raw = open(p, encoding='utf-8').read(); S = json.loads(raw)
L = S['layers']['landslide_odds']; cuts = sorted(L['cuts'], key=lambda c: c['min'])
words = []
for k, c in enumerate(cuts):
    lo, hi = c['min'], (cuts[k + 1]['min'] if k + 1 < len(cuts) else None)
    inside = [b for b in B if b[0][0] >= lo and (hi is None or (b[0][1] is not None and b[0][1] <= hi))]
    obs = [b[1] for b in inside]
    if not obs: sys.exit('no validation band inside class %s' % c['level'])
    if max(obs) < 1: words.append('About an ordinary day or lower (observed %s-%s times)' % (min(obs), max(obs)) if len(obs) > 1 else 'About an ordinary day or lower (observed %s times)' % obs[0])
    else: words.append(('Raised: ' if k == 1 else '') + 'slides about %s times as often as on an ordinary day (observed)' % (obs[0] if len(obs) == 1 else '%s-%s' % (min(obs), max(obs))))
L['words'] = [w[0].upper() + w[1:] for w in words]
L['wordsBasis'] = ('v91.17.283.8: each class names the ratio OBSERVED in the held-out test (data/landslide-odds-model.json validation.served.calibration) '
                   'for days the model put in that class, not the model multiplier; the classes rank days (the model ratio is the ranking score). '
                   'Generated by scripts/gen/gen_landslide_words.py.')
ind = 2 if '\n  "' in raw[:300] else 1
open(p, 'w', encoding='utf-8').write(json.dumps(S, indent=ind, ensure_ascii=('\\u' in raw[:20000])) + ('\n' if raw.endswith('\n') else ''))
print('landslide_odds words:', words)
