/* ══ v91.17.283.8 · audit 9 · THE TESTED DOMAIN OF AN EVIDENCE-BASED ALERT PERMISSION ═══════════════════════════════════════════════
   A level may alert because a test showed skill (the gate's per-level rule, model-gate.resolved.json). The test covered certain forecast
   days and a certain region; outside them the level is UNTESTED, not disproved, and it is served as Indicative with the reason
   "outside the tested domain" (it raises no alert). The domain is read from the evidence file the gate rests on (data/skill-evidence.json,
   heat.client: leads and region, generated by scripts/gen/gen_evidence.py from the evidence files), never typed here.
   Levels whose permission is an owner decision (gate level ownerDecision: true, e.g. heat Low) are not evidence-based and keep their rule.
   When the evidence is not ready (missing, stale), no domain can be confirmed: an evidence-based permission fails closed (Indicative). */
import { skillEvidence } from './evidence.mjs';

export const OUTSIDE_TESTED = 'outside the tested domain';
/* the layers whose evidence lives under a skill-evidence section (the telecom twin reads the same heat evidence) */
export const EVIDENCE_SECTION = Object.freeze({ heat: 'heat', telco_heat: 'heat' });

/* "Sindh and Punjab" / "Sindh, Punjab" -> ['Sindh', 'Punjab'] (the evidence's own words) */
export function regionList(region) { return String(region || '').split(/\s*,\s*|\s+and\s+/i).map((x) => x.trim()).filter(Boolean); }

export function evidenceDomain(dataDir, layer) {
  const sec = EVIDENCE_SECTION[layer]; if (!sec) return null;
  let E = null; try { E = skillEvidence(dataDir); } catch (_) { E = null; }
  if (!E || !E.ready) return { ready: false, why: 'the evidence the permission rests on is not available' + (E && E.why ? ' (' + E.why + ')' : '') };
  const S = E[sec] || {}, C = S.client || null;
  const leads = C && Array.isArray(C.leads) ? C.leads.map(Number).filter(Number.isInteger) : Array.isArray(S.moderateBeatsPersistenceAtLeads) ? S.moderateBeatsPersistenceAtLeads.map(Number) : [];
  const provinces = regionList((C && C.region) || S.region);
  if (!leads.length || !provinces.length) return { ready: false, why: 'the evidence names no tested forecast days or region' };
  return { ready: true, section: sec, leads, provinces, region: (C && C.region) || S.region, window: (C && C.window) || S.window || null, source: 'data/skill-evidence.json ' + sec + (C ? '.client' : '') };
}

/* province of a unit id ('Province|District|Tehsil') or a unit key */
export const provinceOf = (uid) => (uid == null ? null : String(uid).split('|')[0] || null);

/* is (day, place) inside the domain? ctx: { day, uid | province } */
export function inDomain(dom, ctx) {
  if (!dom || !dom.ready) return { ok: false, why: OUTSIDE_TESTED + ': ' + ((dom && dom.why) || 'no tested domain is known') };
  const day = ctx && ctx.day != null ? Number(ctx.day) : null, pv = ctx ? (ctx.province || provinceOf(ctx.uid)) : null;
  const okDay = Number.isInteger(day) && dom.leads.includes(day), okPv = !!pv && dom.provinces.some((p) => p.toLowerCase() === String(pv).toLowerCase());
  if (okDay && okPv) return { ok: true };
  const parts = [];
  if (!okDay) parts.push(day == null || !Number.isInteger(day) ? 'the forecast day is not known here' : 'forecast day ' + day + ' was not tested (tested: day ' + dom.leads.join(' and ') + ')');
  if (!okPv) parts.push(pv ? pv + ' is outside the tested region (' + dom.region + ')' : 'the place is not known here');
  return { ok: false, why: OUTSIDE_TESTED + ': ' + parts.join('; ') + '. Untested, not disproved: shown for context, raises no alert' };
}
